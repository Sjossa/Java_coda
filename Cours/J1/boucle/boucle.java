package J1.boucle;

public class boucle {
    public static void main(String[] args) {

        System.out.println(" boucle for");

        for (int i = 52; i <= 98; i++) {
            System.out.println(i);
        }

        int i = 52;
        System.out.println(" while");

        while (i <= 98) {
            System.out.println(i);
            i++;
        }
        

        System.out.println("do whuile");
        do {
            System.out.println(i);
            i++;
        } while (i <= 98);

    }
}
